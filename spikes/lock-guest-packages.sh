#!/bin/sh
# Resolves the guest image's Alpine packages and writes spikes/guest-packages.lock
# (aarch64) or spikes/guest-packages-x86_64.lock.
#
# The lock names every package the image build installs, including
# dependencies, with its exact version, repository, and SHA-256.
# build-phase1-image.sh installs only those files, offline, so two builds from
# the same lock get the same packages. Run this to take security updates, then
# rebuild and smoke-test (docs/ARTIFACTS.md, "Updating a pin").
#
# Two sets are locked:
#   rootfs  what the guest root filesystem contains;
#   tools   what the build adds to the pinned base image to make the squashfs
#           disk, the stage-1 busybox, and the zstd initramfs.
set -eu

repo_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
# KEEL_GUEST_ARCH selects the architecture, as in build-phase1-image.sh.
case "${KEEL_GUEST_ARCH:-$(uname -m)}" in
arm64 | aarch64)
    guest_arch=aarch64
    platform=linux/arm64
    lock="$repo_root/spikes/guest-packages.lock"
    ;;
x86_64 | amd64)
    guest_arch=x86_64
    platform=linux/amd64
    lock="$repo_root/spikes/guest-packages-x86_64.lock"
    ;;
*)
    echo "unsupported guest architecture: ${KEEL_GUEST_ARCH:-$(uname -m)}" >&2
    exit 1
    ;;
esac
alpine_image=$(sed -n 's/^alpine_image="\(.*\)"$/\1/p' "$repo_root/spikes/build-phase1-image.sh")
test -n "$alpine_image"

rootfs_world="alpine-base bash ca-certificates curl git nodejs tmux
chromium font-dejavu nss-tools
build-base npm py3-pip rust cargo go"
tools_world="squashfs-tools busybox-static zstd"

resolved=$(docker run --rm --platform "$platform" \
    -e ROOTFS_WORLD="$rootfs_world" -e TOOLS_WORLD="$tools_world" \
    -e GUEST_ARCH="$guest_arch" \
    "$alpine_image" sh -eu -c '
apk update -q >/dev/null
installed() {
    awk -F: "/^P:/ { name = \$2 } /^V:/ { print name \"=\" \$2 }" "$1/lib/apk/db/installed" | sort
}
# apk 3 fetch ignores version constraints, so each exact version is looked up
# with apk policy and downloaded from its repository by URL.
emit() {
    set_name=$1
    shift
    mkdir -p "/fetch/$set_name"
    printf "%s\n" "$@" > /wanted
    names=$(sed "s/=.*//" /wanted)
    apk policy $names 2>/dev/null | awk -v wanted=/wanted "
        BEGIN { while ((getline line < wanted) > 0) { split(line, f, \"=\"); want[f[1]] = f[2] } }
        / policy:\$/ { name = \$1; version = \"\"; next }
        /^  [^ ]/ { version = \$1; sub(/:\$/, \"\", version); next }
        /^    https:/ && version == want[name] && !(name in done) { print name, version, \$1; done[name] = 1 }
    " | while read -r name version base; do
        file="$name-$version.apk"
        wget -q -O "/fetch/$set_name/$file" "$base/$GUEST_ARCH/$file"
        sum=$(sha256sum "/fetch/$set_name/$file" | cut -d " " -f 1)
        echo "$set_name ${base##*/} $name-$version $sum"
    done
}

mkdir /root-rootfs
apk add -q --initdb --root /root-rootfs --keys-dir /etc/apk/keys \
    --repositories-file /etc/apk/repositories --no-scripts $ROOTFS_WORLD >/dev/null
emit rootfs $(installed /root-rootfs)

installed "" > /before
apk add -q $TOOLS_WORLD >/dev/null
installed "" > /after
emit tools $(comm -13 /before /after)
')

{
    echo "# Generated by spikes/lock-guest-packages.sh; do not edit by hand."
    echo "# Base image: $alpine_image"
    echo "# rootfs world: $(echo $rootfs_world)"
    echo "# tools world: $tools_world"
    echo "# Fields: set repository name-version sha256"
    echo "$resolved" | sort -k1,1 -k3,3
} > "$lock"
echo "wrote $lock: $(echo "$resolved" | grep -c '^rootfs ') rootfs, $(echo "$resolved" | grep -c '^tools ') tools packages"
